export const ALL_CORPORATE_CATEGORY_NAMES: string[] = CORPORATE_TRAINING_CATEGORIES.map((c) => c.name);

export function getCorporateCategoryByName(name: string): CorporateCategoryDefinition | undefined {
  const lower = name.trim().toLowerCase();
  return CORPORATE_TRAINING_CATEGORIES.find((c) => c.name.toLowerCase() === lower);
}

/**
 * Classifies YouTube video/playlist metadata accurately into granular content types
 * instead of marking every resource as a full course.
 */
export function inferCorporateContentType(params: {
  title?: string;
  description?: string;
  durationMinutes?: number;
  hasPlaylistId?: boolean;
}): CourseContentType {
  if (params.hasPlaylistId) return 'Playlist';
  const text = `${params.title || ''} ${params.description || ''}`.toLowerCase();
  const mins = Number(params.durationMinutes || 0);

  if (/\b(webinar|live session|panel discussion|townhall|summit talk)\b/.test(text)) {
    return 'Webinar';
  }
  if (/\b(workshop|hands[- ]on lab|practical lab|bootcamp|live training)\b/.test(text)) {
    return 'Workshop';
  }
  if (
    /\b(full course|complete course|complete training|masterclass|0 to hero|zero to hero|crash course)\b/.test(text) ||
    mins >= 95
  ) {
    return 'Full course';
  }
  if (/\b(tutorial|how to|step by step|step-by-step|walkthrough|guide for beginners)\b/.test(text)) {
    return 'Tutorial';
  }
  return 'Individual video';
}
